export interface Job {
  id: string
  title: string
  department: string
  location: string
  type: string // Full-time, Part-time, Contract, Internship
  status: "Open" | "Closed"
  description: string
  createdAt: string
  updatedAt: string
  _count?: {
    candidates: number
  }
}

export interface StageHistory {
  id: string
  candidateId: string
  fromStage: string
  toStage: string
  changedById?: string
  changedByName?: string
  changedAt: string
  note?: string
  rejectionReason?: string
}

export interface InterviewNote {
  id: string
  candidateId: string
  scheduledAt?: string
  interviewer?: string
  note: string
  createdAt: string
}

export interface Candidate {
  id: string
  fullName: string
  email: string
  phone?: string
  currentRole?: string
  currentCompany?: string
  experienceYears: number
  skills: string[]
  source: string // LinkedIn, Referral, Job Board, Website, Other
  expectedSalary?: number
  location?: string
  resumeUrl?: string
  notes?: string
  stage: "Applied" | "Screening" | "Interview" | "Technical Round" | "Offer" | "Hired" | "Rejected"
  rating: number // 0 to 5
  rejectionReason?: string
  jobId?: string
  jobTitle?: string
  jobDepartment?: string
  stageHistory: StageHistory[]
  interviewNotes: InterviewNote[]
  createdAt: string
  updatedAt: string
}

